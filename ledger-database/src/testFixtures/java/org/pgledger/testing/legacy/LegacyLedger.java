package org.pgledger.testing.legacy;

import java.sql.Connection;
import java.sql.SQLException;
import java.time.OffsetDateTime;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collection;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.UUID;
import javax.sql.DataSource;
import org.h2.jdbcx.JdbcDataSource;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.jdbc.datasource.DelegatingDataSource;

/**
 * The legacy ledger on an embedded H2 database (MIG-024): the table shapes of the old schema {@code ledger} as
 * {@code sql/10_tables.sql} left them after the migrations {@code 15_defect_case.sql}, {@code 16_common_code.sql} and
 * {@code 17_created_by.sql}, in the ANSI/H2 rendering that the tests of the import use. The PostgreSQL types become: {@code text}
 * a {@code VARCHAR}, {@code jsonb} a {@code CLOB} (the import reads it as text through JDBC either way), {@code uuid} a
 * {@code UUID}, {@code timestamptz} {@code TIMESTAMP WITH TIME ZONE}, {@code name} a {@code VARCHAR}, the identity columns
 * {@code GENERATED BY DEFAULT AS IDENTITY} (the fixture gives its ids). What this rendering cannot hold is left out: the
 * regular expression and function CHECK constraints, the partial unique index of the grants, the deferrable foreign key of
 * {@code merged_into} (the fixture inserts a merge target before the defect merged into it), the functions, views and
 * triggers (nothing the import calls). Tests that need PostgreSQL itself (the timestamptz and jsonb reading of the real
 * DBMS) are test server stage work and are not faked here.
 *
 * <p>There are two accounts on the database: {@link #admin()} writes the fixture, {@link #reader()} is the read-only
 * account the import connects with (it has {@code SELECT} on every table and nothing else, like the {@code ledger_reader}
 * login of the old installer), so a write through it fails.
 */
public final class LegacyLedger implements AutoCloseable {

    /** The legacy schema. */
    public static final String SCHEMA = "ledger";

    /** The installer steps a complete legacy database has recorded in {@code _migration}. */
    public static final Set<String> ALL_STEPS = Set.of("schema", "schema_v2", "defect_case", "common_code",
            "created_by");

    private static final String READER = "LEGACY_READER";
    private static final String READER_SECRET = "legacy-reader-secret-1";

    /** The tables in the order they can be filled (a table after the tables it points to). */
    public static final List<String> TABLES = List.of("project", "common_code", "task", "defect", "defect_fix",
            "defect_case", "defect_task", "defect_relation", "condition", "condition_link", "session_grant", "history",
            "request_receipt", "_migration");

    private static final List<String> DDL = List.of(
            "CREATE SCHEMA ledger",
            "CREATE TABLE ledger._migration (step VARCHAR(100) NOT NULL PRIMARY KEY, done_at TIMESTAMP WITH TIME ZONE NOT NULL,"
                    + " detail CLOB)",
            "CREATE TABLE ledger.project (id VARCHAR(200) NOT NULL PRIMARY KEY, code VARCHAR(64) NOT NULL UNIQUE,"
                    + " title VARCHAR(2000) NOT NULL, created_by VARCHAR(500) NOT NULL)",
            "CREATE TABLE ledger.common_code (code_group VARCHAR(40) NOT NULL, code VARCHAR(100) NOT NULL,"
                    + " name_ko VARCHAR(1000) NOT NULL, name_en VARCHAR(1000) NOT NULL, description_ko VARCHAR(4000) NOT NULL,"
                    + " description_en VARCHAR(4000) NOT NULL, sort_order INTEGER NOT NULL, active BOOLEAN NOT NULL,"
                    + " created_by VARCHAR(500) NOT NULL, PRIMARY KEY (code_group, code))",
            "CREATE TABLE ledger.task (id VARCHAR(500) NOT NULL PRIMARY KEY, project_id VARCHAR(200) NOT NULL,"
                    + " title VARCHAR(2000) NOT NULL, purpose VARCHAR(10000) NOT NULL, success_condition VARCHAR(10000) NOT NULL,"
                    + " state VARCHAR(40) NOT NULL, owner_actor_id VARCHAR(500), origin_ref VARCHAR(2000),"
                    + " origin_quote VARCHAR(5000), version INTEGER NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL,"
                    + " updated_at TIMESTAMP WITH TIME ZONE NOT NULL, created_by VARCHAR(500) NOT NULL,"
                    + " FOREIGN KEY (project_id) REFERENCES ledger.project (id))",
            "CREATE TABLE ledger.defect (id VARCHAR(500) NOT NULL PRIMARY KEY, project_id VARCHAR(200) NOT NULL,"
                    + " title VARCHAR(2000) NOT NULL, category VARCHAR(100) NOT NULL, severity VARCHAR(100) NOT NULL,"
                    + " status VARCHAR(40) NOT NULL, merged_into VARCHAR(500), behavior VARCHAR(10000) NOT NULL,"
                    + " root_cause VARCHAR(10000) NOT NULL, owner_actor_id VARCHAR(500), version INTEGER NOT NULL,"
                    + " created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL,"
                    + " created_by VARCHAR(500) NOT NULL, FOREIGN KEY (project_id) REFERENCES ledger.project (id),"
                    + " FOREIGN KEY (merged_into) REFERENCES ledger.defect (id))",
            "CREATE TABLE ledger.defect_fix (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " defect_id VARCHAR(500) NOT NULL, repo VARCHAR(1000) NOT NULL, commit_sha VARCHAR(40) NOT NULL,"
                    + " branch VARCHAR(1000), ci_ref VARCHAR(2000), ci_conclusion VARCHAR(20),"
                    + " ci_completed_at TIMESTAMP WITH TIME ZONE, recorded_by VARCHAR(500) NOT NULL,"
                    + " recorded_at TIMESTAMP WITH TIME ZONE NOT NULL, imported BOOLEAN DEFAULT FALSE NOT NULL,"
                    + " UNIQUE (defect_id, repo, commit_sha), FOREIGN KEY (defect_id) REFERENCES ledger.defect (id))",
            "CREATE TABLE ledger.defect_case (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " defect_id VARCHAR(500) NOT NULL, observation VARCHAR(10000) NOT NULL, evidence VARCHAR(4000),"
                    + " user_quote VARCHAR(4000), observed_at TIMESTAMP WITH TIME ZONE, recorded_by VARCHAR(500) NOT NULL,"
                    + " recorded_at TIMESTAMP WITH TIME ZONE NOT NULL, FOREIGN KEY (defect_id) REFERENCES ledger.defect (id))",
            "CREATE TABLE ledger.defect_task (defect_id VARCHAR(500) NOT NULL, task_id VARCHAR(500) NOT NULL,"
                    + " created_by VARCHAR(500) NOT NULL, PRIMARY KEY (defect_id, task_id),"
                    + " FOREIGN KEY (defect_id) REFERENCES ledger.defect (id), FOREIGN KEY (task_id) REFERENCES ledger.task (id))",
            "CREATE TABLE ledger.defect_relation (a VARCHAR(500) NOT NULL, b VARCHAR(500) NOT NULL, kind VARCHAR(100) NOT NULL,"
                    + " created_by VARCHAR(500) NOT NULL, PRIMARY KEY (a, b, kind),"
                    + " FOREIGN KEY (a) REFERENCES ledger.defect (id), FOREIGN KEY (b) REFERENCES ledger.defect (id))",
            "CREATE TABLE ledger.condition (id VARCHAR(500) NOT NULL PRIMARY KEY, project_id VARCHAR(200) NOT NULL,"
                    + " release VARCHAR(500) NOT NULL, goal_label VARCHAR(1000), code VARCHAR(200) NOT NULL,"
                    + " condition_text VARCHAR(10000) NOT NULL, state VARCHAR(20) DEFAULT 'UNKNOWN' NOT NULL,"
                    + " version INTEGER NOT NULL, created_by VARCHAR(500) NOT NULL, UNIQUE (project_id, release, code),"
                    + " FOREIGN KEY (project_id) REFERENCES ledger.project (id))",
            "CREATE TABLE ledger.condition_link (condition_id VARCHAR(500) NOT NULL, task_id VARCHAR(500),"
                    + " defect_id VARCHAR(500), created_by VARCHAR(500) NOT NULL,"
                    + " FOREIGN KEY (condition_id) REFERENCES ledger.condition (id),"
                    + " FOREIGN KEY (task_id) REFERENCES ledger.task (id), FOREIGN KEY (defect_id) REFERENCES ledger.defect (id))",
            "CREATE TABLE ledger.session_grant (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " author_id VARCHAR(500) NOT NULL, project VARCHAR(200) NOT NULL, scope VARCHAR(20) NOT NULL,"
                    + " granted_by VARCHAR(500) NOT NULL, granted_at TIMESTAMP WITH TIME ZONE NOT NULL,"
                    + " expires_at TIMESTAMP WITH TIME ZONE, revoked_at TIMESTAMP WITH TIME ZONE, note VARCHAR(1000),"
                    + " FOREIGN KEY (project) REFERENCES ledger.project (id))",
            "CREATE TABLE ledger.history (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " at TIMESTAMP WITH TIME ZONE NOT NULL, author_id VARCHAR(500) NOT NULL, login VARCHAR(100) NOT NULL,"
                    + " actor_assurance VARCHAR(40) NOT NULL, entity VARCHAR(40) NOT NULL, entity_id VARCHAR(1000) NOT NULL,"
                    + " op VARCHAR(40) NOT NULL, from_state VARCHAR(40), to_state VARCHAR(40), changes CLOB NOT NULL,"
                    + " reason VARCHAR(10000) NOT NULL, evidence_uri VARCHAR(4000), evidence_sha256 VARCHAR(64),"
                    + " corrects_id BIGINT, request_id UUID NOT NULL, legacy_ref VARCHAR(500),"
                    + " FOREIGN KEY (corrects_id) REFERENCES ledger.history (id))",
            "CREATE TABLE ledger.request_receipt (request_id UUID NOT NULL PRIMARY KEY, operation VARCHAR(100) NOT NULL,"
                    + " payload_sha256 VARCHAR(64) NOT NULL, author_id VARCHAR(500) NOT NULL, login VARCHAR(100) NOT NULL,"
                    + " response CLOB, created_at TIMESTAMP WITH TIME ZONE NOT NULL)");

    private final String name;
    private final JdbcDataSource admin;
    private final JdbcClient jdbc;

    private LegacyLedger(String name) {
        this.name = name;
        this.admin = dataSource(name, "SA", "");
        this.jdbc = JdbcClient.create(admin);
    }

    private static JdbcDataSource dataSource(String name, String user, String secret) {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:" + name + ";DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=60000");
        dataSource.setUser(user);
        dataSource.setPassword(secret);
        return dataSource;
    }

    /** A new legacy database with the whole schema and every installer step recorded. */
    public static LegacyLedger create() {
        return create(ALL_STEPS);
    }

    /** A new legacy database with the whole schema and only these installer steps recorded in {@code _migration}. */
    public static LegacyLedger create(Collection<String> steps) {
        LegacyLedger ledger = new LegacyLedger("legacy" + UUID.randomUUID().toString().replace("-", ""));
        for (String statement : DDL) {
            ledger.jdbc.sql(statement).update();
        }
        for (String step : steps) {
            ledger.insert("_migration", "step", step, "done_at", OffsetDateTime.parse("2026-01-01T00:00:00Z"));
        }
        ledger.jdbc.sql("CREATE USER " + READER + " PASSWORD '" + READER_SECRET + "'").update();
        for (String table : TABLES) {
            ledger.jdbc.sql("GRANT SELECT ON " + SCHEMA + "." + table + " TO " + READER).update();
        }
        return ledger;
    }

    /** A database that has no legacy schema at all. */
    public static LegacyLedger withoutSchema() {
        return new LegacyLedger("legacy" + UUID.randomUUID().toString().replace("-", ""));
    }

    /** The connection of the fixture: it writes the data. */
    public DataSource admin() {
        return admin;
    }

    /** The read-only account the import connects with (SELECT only). */
    public DataSource reader() {
        return dataSource(name, READER, READER_SECRET);
    }

    /**
     * As {@link #reader()}, with the database session in the time zone {@code zone} (MIG-027): every connection runs
     * {@code SET TIME ZONE} first, so the legacy session zone is whatever the test says.
     */
    public DataSource reader(String zone) {
        return new DelegatingDataSource(reader()) {
            @Override
            public Connection getConnection() throws SQLException {
                Connection connection = super.getConnection();
                try (var statement = connection.createStatement()) {
                    statement.execute("SET TIME ZONE '" + zone + "'");
                }
                return connection;
            }
        };
    }

    /** Inserts one row of a legacy table; the arguments are column names and values, in pairs. */
    public LegacyLedger insert(String table, Object... namesAndValues) {
        List<String> columns = new ArrayList<>();
        List<Object> values = new ArrayList<>();
        for (int i = 0; i < namesAndValues.length; i += 2) {
            columns.add((String) namesAndValues[i]);
            values.add(namesAndValues[i + 1]);
        }
        String marks = String.join(", ", columns.stream().map(column -> "?").toList());
        jdbc.sql("INSERT INTO " + SCHEMA + "." + table + " (" + String.join(", ", columns) + ") VALUES (" + marks + ")")
                .params(values).update();
        return this;
    }

    /** Runs a statement on the legacy database with the fixture's account (a test that corrects or damages a row). */
    public int update(String sql, Object... arguments) {
        return jdbc.sql(sql).params(Arrays.asList(arguments)).update();
    }

    /** The rows of a query on the legacy database (column names are the upper-case names of H2). */
    public List<Map<String, Object>> rows(String sql, Object... arguments) {
        return jdbc.sql(sql).params(Arrays.asList(arguments)).query().listOfRows();
    }

    /** The number of rows of a legacy table. */
    public long count(String table) {
        return jdbc.sql("SELECT COUNT(*) FROM " + SCHEMA + "." + table).query(Long.class).single();
    }

    /** The names of the objects of the legacy schema (tables, views), for the check that the import creates none. */
    public List<String> objects() {
        return jdbc.sql("SELECT table_name FROM information_schema.tables WHERE table_schema = 'LEDGER' ORDER BY table_name")
                .query(String.class).list();
    }

    /** A time value of the legacy columns, from ISO-8601 text with an offset (the instant it names is what the import keeps). */
    public static OffsetDateTime at(String iso) {
        return OffsetDateTime.parse(iso);
    }

    @Override
    public void close() {
        jdbc.sql("SHUTDOWN").update();
    }
}
